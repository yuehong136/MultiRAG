@pytest.fixture
def document_files(runtime_upload_api: dict[str, Any], monkeypatch: pytest.MonkeyPatch) -> Iterator[dict[str, Any]]:
    env = runtime_upload_api
    owner, other = env["owners"]
    datasets = {key: uuid4().hex for key in ("own", "foreign")}
    documents = {key: uuid4().hex for key in ("own", "foreign", "html", "empty")}
    attachment = uuid4().hex
    reads: list[tuple[str, str]] = []
    storage = env["storage_adapter"]
    reader = storage.get_bytes

    def observed_read(namespace: str, key: str) -> bytes | None:
        reads.append((namespace, key))
        return reader(namespace, key)

    monkeypatch.setattr(storage, "get_bytes", observed_read)
    try:
        with Session(env["engine"]) as db:
            for key, kb_id in datasets.items():
                tenant = owner if key == "own" else other
                db.add(Knowledgebase(id=kb_id, tenant_id=tenant, name=key, embd_id="", created_by=tenant))
            for key, doc_id in documents.items():
                db.add(
                    Document(
                        id=doc_id,
                        kb_id=datasets["foreign" if key == "foreign" else "own"],
                        name="文档." + ("html" if key == "html" else "txt"),
                        location=key,
                        parser_id="naive",
                        type="doc",
                        created_by=owner,
                    )
                )
            db.commit()
        for key, doc_id in documents.items():
            storage.put(datasets["foreign" if key == "foreign" else "own"], key, b"" if key == "empty" else key.encode() + b"\x00 bytes")
        storage.put(owner, attachment, b"generated bytes")
        from api.apps import manager

        yield dict(env, datasets=datasets, docs=documents, attachment=attachment, reads=reads, foreign_jwt=manager.create_access_token(data={"sub": f"{other}@upload.test"}))
    finally:
        with Session(env["engine"]) as db:
            conditions = [
                (Document, Document.id.in_(documents.values())),
                (Knowledgebase, Knowledgebase.id.in_(datasets.values())),
                (UserTenant, sa.and_(UserTenant.tenant_id == owner, UserTenant.user_id == other)),
            ]
            for model, condition in conditions:
                db.execute(sa.delete(model).where(condition))
            db.commit()
        with env["engine"].connect() as db:
            assert all(db.scalar(sa.select(sa.func.count()).select_from(model).where(condition)) == 0 for model, condition in conditions)
        env["record"]["document_rows_removed"] = True


def request_file(env: dict[str, Any], path: str, *, token: str | None = "owner") -> requests.Response:
    value = env["jwt"] if token == "owner" else env["foreign_jwt"]
    headers = {"Authorization": f"Bearer {value}"} if token else {}
    return requests.get(env["base"] + path, headers=headers, timeout=30)


def snapshot(env: dict[str, Any]) -> tuple[list[Any], dict[str, bytes]]:
    with Session(env["engine"]) as db:
        rows = [dict(row._mapping) for row in db.execute(sa.select(Document.__table__).where(Document.id.in_(env["docs"].values())).order_by(Document.id))]
    objects = {item.object_name: read_object(env["storage"], env["bucket"], item.object_name) for item in env["storage"].list_objects(env["bucket"], recursive=True)}
    return rows, objects


def test_document_bytes_headers_and_resource_separation(document_files: dict[str, Any]) -> None:
    env = document_files
    before = snapshot(env)
    for action in ("preview", "download"):
        response = request_file(env, f"/api/v1/documents/{env['docs']['own']}/{action}")
        assert response.status_code == 200 and response.content == b"own\x00 bytes"
        assert response.headers["Content-Type"] == "text/plain"
        assert response.headers["X-Content-Type-Options"] == "nosniff"
        assert response.headers["Cache-Control"] == "no-store"
        if action == "download":
            assert "attachment; filename*=UTF-8''" in response.headers["Content-Disposition"]
    html = request_file(env, f"/api/v1/documents/{env['docs']['html']}/preview")
    assert html.status_code == 200 and html.headers["Content-Disposition"].startswith("attachment")
    empty = request_file(env, f"/api/v1/documents/{env['docs']['empty']}/preview")
    assert empty.status_code == 200 and empty.content == b""
    runtime_path = f"/api/v1/documents/runtime/{env['attachment']}/download?ext=txt"
    runtime = request_file(env, runtime_path)
    assert runtime.status_code == 200 and runtime.content == b"generated bytes"
    assert runtime.headers["Content-Type"] == "text/plain"
    assert snapshot(env) == before
    env["reads"].clear()
    # No fallback from a dataset ID into the user's generated-file namespace.
    assert request_file(env, f"/api/v1/documents/{env['attachment']}/download").json() == {"code": 102, "message": "Document not found!", "data": None}
    assert not env["reads"]
    # A knowledgebase document is absent from the generated-file namespace.
    assert request_file(env, f"/api/v1/documents/runtime/{env['docs']['own']}/download").status_code == 404
    assert request_file(env, runtime_path, token="foreign").status_code == 404
    assert request_file(env, runtime_path, token=None).status_code == 401
    assert snapshot(env) == before
    env["record"]["document_file_readback"] = {"sql_and_objects_unchanged": True, "dataset_bytes": True, "runtime_bytes": True, "html_attachment": True, "empty_bytes": True}
    env["record_path"].write_text(json.dumps(env["record"], indent=2))


def test_document_authorization_and_retired_preview(document_files: dict[str, Any]) -> None:
    env = document_files
    before = snapshot(env)
    for action in ("preview", "download"):
        foreign = request_file(env, f"/api/v1/documents/{env['docs']['foreign']}/{action}")
        missing = request_file(env, f"/api/v1/documents/{uuid4().hex}/{action}")
        assert foreign.status_code == missing.status_code == 404
        assert foreign.json() == missing.json() == {"code": 102, "message": "Document not found!", "data": None}
        assert request_file(env, f"/api/v1/documents/{env['docs']['own']}/{action}", token=None).status_code == 401
    assert not env["reads"]
    assert request_file(env, f"/v1/document/get/{env['docs']['own']}").status_code == 404
    from api.apps import app

    paths = app.openapi()["paths"]
    assert "/v1/document/get/{doc_id}" not in paths
    assert "/api/v1/documents/{doc_id}/preview" in paths
    with Session(env["engine"]) as db:
        db.add(UserTenant(id=uuid4().hex, tenant_id=env["owners"][0], user_id=env["owners"][1], role="normal", status="1", invited_by=env["owners"][0]))
        db.commit()
    path = f"/api/v1/documents/{env['docs']['own']}"
    response = request_file(env, path + "/preview", token="foreign")
    assert response.status_code == 200 and response.content == b"own\x00 bytes"
    env["reads"].clear()
    response = request_file(env, path + "/download", token="foreign")
    assert response.status_code == 403 and response.json()["code"] == 109
    assert not env["reads"]
    with Session(env["engine"]) as db:
        db.execute(sa.update(UserTenant).where(UserTenant.tenant_id == env["owners"][0], UserTenant.user_id == env["owners"][1]).values(role="admin"))
        db.commit()
    assert request_file(env, path + "/download", token="foreign").content == b"own\x00 bytes"
    assert snapshot(env) == before
