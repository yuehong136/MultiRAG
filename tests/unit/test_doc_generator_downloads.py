def test_doc_generator_resolves_mixed_stream_and_structured_variables():
    generator = object.__new__(DocGenerator)
    generator._param = SimpleNamespace(
        content="Answer={begin@answer}; metadata={begin@metadata}; missing={begin@missing}",
    )
    values = {
        "begin@answer": partial(lambda: iter(["hel", "lo"])),
        "begin@metadata": {"status": "ok"},
        "begin@missing": None,
    }
    generator._canvas = MagicMock()
    generator._canvas.get_variable_value.side_effect = values.get

    assert generator._resolve_content({}) == 'Answer=hello; metadata={"status": "ok"}; missing='


@pytest.mark.parametrize(
    ("output_format", "mime_type"),
    [
        ("pdf", "application/pdf"),
        ("docx", "application/vnd.openxmlformats-officedocument.wordprocessingml.document"),
        ("txt", "text/plain"),
        ("markdown", "text/markdown"),
        ("html", "text/html"),
    ],
)
async def test_generator_base64_matches_file_and_message_downloads(monkeypatch: pytest.MonkeyPatch, tmp_path: Path, caplog: pytest.LogCaptureFixture, output_format: str, mime_type: str) -> None:
    raw = b"Private generated bytes\x00\xff\xfe\n" + "中文".encode()
    generated = tmp_path / "report.bin"
    generated.write_bytes(raw)
    objects: dict[tuple[str, str], bytes] = {}
    storage = SimpleNamespace(put=lambda tenant, doc_id, data: objects.__setitem__((tenant, doc_id), data))
    monkeypatch.setattr(settings, "STORAGE_IMPL", storage)
    generator = object.__new__(DocGenerator)
    generator._param = DocGeneratorParam()
    generator._param.output_format = output_format
    generator._param.content = "Private content marker"
    generator._canvas = SimpleNamespace(get_tenant_id=lambda: "owner")
    monkeypatch.setattr(generator, f"_generate_{output_format}", lambda content: (str(generated), generated.read_bytes()))

    with caplog.at_level(logging.INFO):
        info = generator._invoke()
    assert set(info) == {"doc_id", "filename", "mime_type", "size", "base64", "include_download_info_in_content"}
    assert info["filename"] == generated.name and info["mime_type"] == mime_type and info["size"] == len(raw)
    assert base64.b64decode(info["base64"], validate=True) == objects[("owner", info["doc_id"])] == raw
    assert json.loads(generator.output("download")) == info
    assert not generated.exists()
    assert info["base64"] not in caplog.text and "Private content marker" not in caplog.text

    message = object.__new__(Message)
    message._param = MessageParam()
    message._canvas = SimpleNamespace(get_variable_value=lambda exp: generator.output("download"))
    monkeypatch.setattr(message, "check_if_canceled", lambda context: False)
    monkeypatch.setattr(message, "_convert_content", lambda content: None)
    rendered = "".join([part async for part in message._stream("Ready[{DocGenerator:one@download}].")])
    assert rendered == "Ready[]."
    assert message.output("downloads") == [Message._normalize_download_info(info)]


def test_generator_storage_failure_has_no_download_and_cleans_file(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    generator = object.__new__(DocGenerator)
    generator._param = DocGeneratorParam()
    generator._param.output_format = "txt"
    generator._param.content = "private content"
    generator._canvas = SimpleNamespace(get_tenant_id=lambda: "owner")
    path = tmp_path / "report.txt"
    path.write_bytes(b"private content")
    monkeypatch.setattr(generator, "_generate_txt", lambda content: (str(path), path.read_bytes()))

    def fail(*args: Any) -> None:
        raise OSError("storage unavailable")

    monkeypatch.setattr(settings, "STORAGE_IMPL", SimpleNamespace(put=fail))
    with pytest.raises(OSError, match="storage unavailable"):
        generator._invoke()
    assert generator.output("download") == ""
    assert "storage unavailable" in generator.output("_ERROR")
    assert not path.exists()
