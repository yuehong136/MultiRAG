"""Opt-in isolated Chrome/browser-use acceptance with a loopback model.

Run with ANONYMIZED_TELEMETRY=false, BROWSER_USE_CLOUD_SYNC=false,
BROWSER_USE_EXECUTABLE_PATH and MULTIRAG_BROWSER_EVIDENCE pointing to owned paths.
Uses no provider credentials or user browser profile. SQL/MinIO acceptance lives
in tests/integration/test_browser_component_files.py.
"""

import asyncio
import json
import os
import re
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from types import SimpleNamespace
from typing import Any

import psutil
from browser_use.llm import ChatOpenAI

from agent.component.browser import Browser, BrowserParam


def main() -> None:
    root = Path(os.environ["MULTIRAG_BROWSER_EVIDENCE"])
    root.mkdir(parents=True, exist_ok=True)
    record: dict[str, Any] = {"root": str(root), "port": None, "actions": [], "uploads": [], "downloads": 0}
    manifest = root / "chromium.json"
    mode = {"value": "actions", "step": 0}
    received, release = threading.Event(), threading.Event()
    upload = root / "upload.txt"
    upload.write_bytes(b"browser input bytes")

    def save() -> None:
        manifest.write_text(json.dumps(record, indent=2))

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *_args: Any) -> None:
            pass

        def reply(self, body: bytes, mime: str = "text/html") -> None:
            self.send_response(200)
            self.send_header("Content-Type", mime)
            self.send_header("Content-Length", str(len(body)))
            if mime == "application/octet-stream":
                self.send_header("Content-Disposition", 'attachment; filename="report.txt"')
            self.end_headers()
            try:
                self.wfile.write(body)
            except (BrokenPipeError, ConnectionResetError):
                pass

        def do_GET(self) -> None:
            if self.path.startswith("/download"):
                record["downloads"] += 1
                self.reply(b"browser download bytes", "application/octet-stream")
            else:
                self.reply(b'<!doctype html><title>Owned Browser Acceptance</title><h1>Browser G</h1><input type="file" id="upload"><a href="/download" download="report.txt">Download report</a>')

        def do_POST(self) -> None:
            body = self.rfile.read(int(self.headers.get("Content-Length", "0")))
            if self.path == "/uploaded":
                record["uploads"].append(body.decode())
                self.reply(b"ok", "text/plain")
                return
            request = json.loads(body)
            text = json.dumps(request["messages"], ensure_ascii=False)
            step = mode["step"]
            mode["step"] += 1
            (root / f"model-{mode['value']}-{step}.json").write_text(json.dumps(request, ensure_ascii=False))
            if mode["value"] == "cancel":
                received.set()
                release.wait(30)
            if str(request["messages"][0].get("content", "")).startswith("You are an expert judge"):
                content: dict[str, Any] = {"verdict": True, "reasoning": "Independent handler assertions check actions", "failure_reason": None, "impossible_task": False, "reached_captcha": False}
            else:
                if mode["value"] == "actions" and step == 0:
                    # DOM indices are generated by browser-use; select its actual input.
                    lines = text.replace("\\n", "\n").splitlines()
                    candidates = [line for line in lines if "input" in line.lower() and "file" in line.lower() and re.search(r"\[\d+\]|<\d+|index=", line)]
                    indices = re.findall(r"\[(\d+)\]|<(\d+)|index=[\"']?(\d+)", "\n".join(candidates))
                    index = int(next((part for group in indices for part in group if part), "1"))
                    action = {"upload_file": {"index": index, "path": str(upload)}}
                elif mode["value"] == "actions" and step == 1:
                    action = {
                        "evaluate": {
                            "code": "(async()=>{const f=document.querySelector('#upload').files[0];await fetch('/uploaded',{method:'POST',body:await f.arrayBuffer()});localStorage.setItem('actor-secret','G');document.cookie='actor=G;path=/';document.querySelector('a').click();return 'uploaded-and-downloaded'})()"
                        }
                    }
                elif mode["value"] in {"same", "other"} and step == 0:
                    action = {"evaluate": {"code": "(()=>{const value=localStorage.getItem('actor-secret');fetch('/uploaded',{method:'POST',body:'profile:'+value});return value})()"}}
                else:
                    action = {"done": {"text": "controlled browser complete", "success": True}}
                record["actions"].append(action)
                content = {"evaluation_previous_goal": "controlled step", "memory": "acceptance", "next_goal": "continue", "action": [action]}
            response = {
                "id": "controlled",
                "object": "chat.completion",
                "created": 1,
                "model": "controlled-browser",
                "choices": [{"index": 0, "message": {"role": "assistant", "content": json.dumps(content)}, "finish_reason": "stop"}],
                "usage": {"prompt_tokens": 1, "completion_tokens": 1, "total_tokens": 2},
            }
            self.reply(json.dumps(response).encode(), "application/json")

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    port = server.server_port
    record["port"] = port
    save()  # Listener bound, not started; root owns all profile/temp writes.
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    os.environ["MULTIRAG_BROWSER_PROFILE_ROOT"] = str(root / "profiles")

    async def verify() -> None:
        obj = object.__new__(Browser)
        obj._id = "Browser:real"
        obj._param = BrowserParam()
        obj._param.llm_id = "controlled-browser@OpenAI"
        obj._param.max_steps = 6
        obj._canvas = SimpleNamespace(get_tenant_id=lambda: "tenant", artifact_owner_id="actor-A", _id="graph", is_canceled=lambda: False)

        async def build() -> Any:
            return ChatOpenAI(
                model="controlled-browser",
                api_key="loopback-test-only",
                base_url=f"http://127.0.0.1:{port}/v1",
                temperature=0,
                max_retries=0,
                add_schema_to_system_prompt=True,
                dont_force_structured_output=True,
            )

        obj._build_browser_llm = build
        downloads = root / "downloads"
        downloads.mkdir(exist_ok=True)
        try:
            for value in ("actions", "same", "other"):
                mode.update(value=value, step=0)
                if value == "other":
                    obj._canvas.artifact_owner_id = "actor-B"
                async with obj._profile() as profile:
                    history = await obj._run_browser_use_async(f"Visit http://127.0.0.1:{port}/ and perform the controlled task", str(downloads), [str(upload)], profile)
                    assert obj._extract_history_text(history) == "controlled browser complete"
                save()
            assert "browser input bytes" in record["uploads"], record["uploads"]
            assert "profile:G" in record["uploads"] and "profile:null" in record["uploads"], record["uploads"]
            assert any(path.read_bytes() == b"browser download bytes" for path in downloads.rglob("*") if path.is_file())
            mode.update(value="cancel", step=0)
            obj._param.persist_session = False
            async with obj._profile() as profile:
                task = asyncio.create_task(obj._run_browser_use_async(f"Visit http://127.0.0.1:{port}/", str(downloads), [], profile))
                assert await asyncio.to_thread(received.wait, 30)
                task.cancel()
                try:
                    await task
                except asyncio.CancelledError:
                    record["cancellation_propagated"] = True
                finally:
                    release.set()
            assert not profile.exists()
            record["ephemeral_profile_removed"] = True
        finally:
            for actor in ("actor-A", "actor-B"):
                obj._canvas.artifact_owner_id = actor
                obj._param.persist_session = True
                await obj.clear_persistent_profile()

    try:
        asyncio.run(verify())
    finally:
        release.set()
        server.shutdown()
        server.server_close()
        thread.join(5)
        alive = []
        for process in psutil.process_iter(["pid", "cmdline", "name"]):
            try:
                cmdline = " ".join(process.info["cmdline"] or [])
                if str(root) in cmdline and "chrome" in str(process.info["name"]).lower():
                    alive.append(process.pid)
            except (psutil.NoSuchProcess, psutil.AccessDenied):
                pass
        record["remaining_chrome_pids"] = alive
        record["listener_closed"] = not thread.is_alive()
        save()
        assert not alive and not thread.is_alive(), record
    print(json.dumps({key: value for key, value in record.items() if key != "actions"}, indent=2))


if __name__ == "__main__":
    main()
