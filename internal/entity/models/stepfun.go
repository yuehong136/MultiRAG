// AudioSpeech convert text to audio
func (s *StepFunModel) AudioSpeech(modelName *string, audioContent *string, apiConfig *APIConfig, ttsConfig *TTSConfig) (*TTSResponse, error) {
	if modelName == nil || strings.TrimSpace(*modelName) == "" {
		return nil, fmt.Errorf("model name is required")
	}

	if err := s.baseModel.APIConfigCheck(apiConfig); err != nil {
		return nil, err
	}

	// TODO Test it
	if audioContent == nil || *audioContent == "" {
		return nil, fmt.Errorf("audio content is empty")
	}

	resolvedBaseURL, err := s.baseModel.GetBaseURL(apiConfig)
	if err != nil {
		return nil, err
	}
	url := fmt.Sprintf("%s/%s", resolvedBaseURL, s.baseModel.URLSuffix.TTS)

	reqBody := map[string]interface{}{
		"model": *modelName,
		"input": *audioContent,
	}

	if ttsConfig != nil && ttsConfig.Params != nil {
		for key, value := range ttsConfig.Params {
			reqBody[key] = value
		}
	}
	if ttsConfig != nil && ttsConfig.Format != "" {
		reqBody["response_format"] = ttsConfig.Format
	}

	jsonData, err := json.Marshal(reqBody)
	if err != nil {
		return nil, fmt.Errorf("failed to marshal request: %w", err)
	}

	req, err := http.NewRequestWithContext(apiConfig.RequestContext(), "POST", url, bytes.NewBuffer(jsonData))
	if err != nil {
		return nil, fmt.Errorf("failed to create request: %w", err)
	}

	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", fmt.Sprintf("Bearer %s", *apiConfig.ApiKey))

	resp, err := s.baseModel.httpClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("failed to send request: %w", err)
	}
	defer resp.Body.Close()

	body, err := io.ReadAll(io.LimitReader(resp.Body, (20<<20)+1))
	if err != nil {
		return nil, fmt.Errorf("failed to read response body: %w", err)
	}

	if len(body) > 20<<20 {
		return nil, fmt.Errorf("media response exceeds limit")
	}

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s - %s", resp.Status, "[redacted]")
	}

	if len(body) == 0 || json.Valid(body) || strings.HasPrefix(strings.ToLower(resp.Header.Get("Content-Type")), "application/json") {
		return nil, fmt.Errorf("speech response contains no audio")
	}
	return &TTSResponse{Audio: body}, nil
}

// AudioSpeechWithSender for Streaming TTS
func (s *StepFunModel) AudioSpeechWithSender(modelName *string, audioContent *string, apiConfig *APIConfig, ttsConfig *TTSConfig, sender func(*string, *string) error) error {
	if modelName == nil || strings.TrimSpace(*modelName) == "" {
		return fmt.Errorf("model name is required")
	}
	if sender == nil {
		return fmt.Errorf("sender is required")
	}

	if err := s.baseModel.APIConfigCheck(apiConfig); err != nil {
		return err
	}

	if audioContent == nil || *audioContent == "" {
		return fmt.Errorf("audio content is empty")
	}

	resolvedBaseURL, err := s.baseModel.GetBaseURL(apiConfig)
	if err != nil {
		return err
	}
	url := fmt.Sprintf("%s/%s", resolvedBaseURL, s.baseModel.URLSuffix.TTS)

	reqBody := map[string]interface{}{
		"model":         *modelName,
		"input":         *audioContent,
		"stream_format": "sse",
	}

	if ttsConfig != nil && ttsConfig.Params != nil {
		for key, value := range ttsConfig.Params {
			reqBody[key] = value
		}
	}
	if ttsConfig != nil && ttsConfig.Format != "" {
		reqBody["response_format"] = ttsConfig.Format
	}

	jsonData, err := json.Marshal(reqBody)
	if err != nil {
		return fmt.Errorf("failed to marshal request: %w", err)
	}

	req, err := http.NewRequestWithContext(apiConfig.RequestContext(), "POST", url, bytes.NewBuffer(jsonData))
	if err != nil {
		return fmt.Errorf("failed to create request: %w", err)
	}

	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", fmt.Sprintf("Bearer %s", *apiConfig.ApiKey))

	resp, err := s.baseModel.httpClient.Do(req)
	if err != nil {
		return fmt.Errorf("failed to send request: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("StepFun stream TTS API error: %d - %s", resp.StatusCode, "[redacted]")
	}

	type ttsEvent struct {
		Type  string          `json:"type"`
		Audio string          `json:"audio"`
		Error json.RawMessage `json:"error"`
	}
	totalAudio := 0
	sawTerminal := false
	done, err := ParseSSEStream[ttsEvent](resp.Body, func(event ttsEvent) error {
		if (len(event.Error) > 0 && string(event.Error) != "null") || event.Type == "speech.audio.error" {
			return fmt.Errorf("StepFun stream generation failed")
		}
		switch event.Type {
		case "speech.audio.done":
			sawTerminal = true
		case "speech.audio.delta":
			if sawTerminal || event.Audio == "" {
				return fmt.Errorf("invalid StepFun audio frame")
			}
			audio, err := base64.StdEncoding.Strict().DecodeString(event.Audio)
			if err != nil || len(audio) == 0 {
				return fmt.Errorf("invalid StepFun audio encoding")
			}
			totalAudio += len(audio)
			if totalAudio > 20<<20 {
				return fmt.Errorf("speech stream exceeds limit")
			}
			chunk := string(audio)
			if err := sender(&chunk, nil); err != nil {
				return err
			}
			return apiConfig.RequestContext().Err()
		case "speech.audio.start", "speech.audio.started":
		default:
			return fmt.Errorf("invalid StepFun stream event")
		}
		return nil
	})
	if err != nil {
		return fmt.Errorf("failed to scan response body: %w", err)
	}
	if totalAudio == 0 || (!sawTerminal && !done) {
		return fmt.Errorf("StepFun speech stream incomplete")
	}
	return nil
}

