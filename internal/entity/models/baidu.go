// OCRFile OCR file
type qianfanOCRResponse struct {
	Id     string `json:"id"`
	Result struct {
		LayoutParsingResults []struct {
			Markdown struct {
				Text string `json:"text"`
			} `json:"markdown"`
		} `json:"layoutParsingResults"`
	} `json:"result"`
}

func (b *BaiduModel) OCRFile(modelName *string, content []byte, fileURL *string, apiConfig *APIConfig, ocrConfig *OCRConfig) (*OCRFileResponse, error) {
	if modelName == nil || strings.TrimSpace(*modelName) == "" {
		return nil, fmt.Errorf("model name is required")
	}

	if err := b.baseModel.APIConfigCheck(apiConfig); err != nil {
		return nil, err
	}

	if (fileURL == nil || *fileURL == "") && (content == nil || len(content) == 0) {
		return nil, fmt.Errorf("image url or content is required")
	}
	if modelName == nil || strings.TrimSpace(*modelName) == "" {
		return nil, fmt.Errorf("model name is required")
	}

	resolvedBaseURL, err := b.baseModel.GetBaseURL(apiConfig)
	if err != nil {
		return nil, err
	}
	url := fmt.Sprintf("%s/%s", resolvedBaseURL, b.baseModel.URLSuffix.OCR)

	reqData := map[string]interface{}{
		"model": *modelName,
	}

	if fileURL != nil && *fileURL != "" {
		reqData["file"] = *fileURL
		if parsed, e := neturl.Parse(*fileURL); e == nil && strings.HasSuffix(strings.ToLower(parsed.Path), ".pdf") {
			reqData["fileType"] = 0 // PDF
		} else {
			reqData["fileType"] = 1 // img
		}
	} else if content != nil && len(content) > 0 {
		reqData["file"] = base64.StdEncoding.EncodeToString(content)

		mimeType := http.DetectContentType(content)
		if strings.Contains(mimeType, "pdf") {
			reqData["fileType"] = 0 // PDF
		} else {
			reqData["fileType"] = 1 // img
		}
	}

	jsonData, err := json.Marshal(reqData)
	if err != nil {
		return nil, fmt.Errorf("failed to marshal json payload: %w", err)
	}

	ctx, cancel := context.WithTimeout(apiConfig.RequestContext(), longOpCallTimeout)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, "POST", url, bytes.NewBuffer(jsonData))
	if err != nil {
		return nil, fmt.Errorf("failed to create request: %w", err)
	}

	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", fmt.Sprintf("Bearer %s", *apiConfig.ApiKey))

	resp, err := b.baseModel.httpClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("failed to send request: %w", err)
	}
	defer resp.Body.Close()

	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, fmt.Errorf("failed to read response: %w", err)
	}

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("API error: %s, body: %s", resp.Status, "[redacted]")
	}

	var apiResponse qianfanOCRResponse
	if err = json.Unmarshal(body, &apiResponse); err != nil {
		return nil, fmt.Errorf("failed to parse response json: %w", err)
	}

	var envelope map[string]json.RawMessage
	if json.Unmarshal(body, &envelope) != nil || envelope["result"] == nil || (envelope["error_code"] != nil && string(envelope["error_code"]) != "0") {
		return nil, fmt.Errorf("invalid OCR response")
	}
	pages := apiResponse.Result.LayoutParsingResults
	if len(pages) == 0 {
		return nil, fmt.Errorf("no parsing results returned from API")
	}
	texts := make([]string, 0, len(pages))
	for _, page := range pages {
		if strings.TrimSpace(page.Markdown.Text) == "" {
			return nil, fmt.Errorf("OCR page missing text")
		}
		texts = append(texts, page.Markdown.Text)
	}
	extractedText := strings.Join(texts, "\n\n")

	var ocrResponse = OCRFileResponse{
		Text: &extractedText,
	}

	return &ocrResponse, nil
}

