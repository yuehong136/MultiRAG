func TestMetadataCheckedPropagatesModelFailureAndCancellation(t *testing.T) {
	model, driver := metadataModel(`{"conditions":[]}`)
	failure := errors.New("controlled model failure")
	driver.failure = failure
	if _, _, err := ApplyMetaDataFilter(t.Context(), map[string]interface{}{"method": "auto"}, metadataFixture(), "q", model, nil, nil); !errors.Is(err, failure) {
		t.Fatal("model failure lost", err)
	}
	for _, after := range []bool{false, true} {
		ctx, cancel := context.WithCancel(t.Context())
		model, driver := metadataModel(`{"conditions":[]}`)
		if after {
			driver.check = func(api *models.APIConfig, _ []models.Message) {
				if api.Context != ctx {
					t.Fatal("request context not propagated")
				}
				cancel()
			}
		} else {
			cancel()
		}
		if _, _, err := ApplyMetaDataFilter(ctx, map[string]interface{}{"method": "auto"}, metadataFixture(), "q", model, nil, nil); !errors.Is(err, context.Canceled) {
			t.Fatal(err)
		}
		if !after && driver.calls != 0 {
			t.Fatal("canceled request reached model")
		}
		cancel()
	}
}
func TestMetadataGeneratedJSONRequiresConditionsArray(t *testing.T) {
	for _, payload := range []string{"null", "{}", `{"conditions":null}`, `{"conditions":{}}`, `{"conditions":[],"logic":null}`, `{"conditions":[null]}`, `{"conditions":[{"key":"status","op":"not in","value":false}]}`, `{"conditions":[]}`, `invalid-json`} {
		model, driver := metadataModel(payload)
		ids, empty, err := ApplyMetaDataFilter(t.Context(), map[string]interface{}{"method": "auto"}, metadataFixture(), "q", model, nil, nil)
		if driver.calls != 1 {
			t.Fatal("model not called")
		}
		if payload == `{"conditions":[]}` {
			if err != nil || empty || ids != nil {
				t.Fatal("valid optional filter fallback changed", ids, empty, err)
			}
		} else if err == nil {
			t.Fatal("malformed model output broadened retrieval", payload, ids, empty)
		}
	}
}

func TestMetadataGeneratedFilterPreservesExactNumericOperandAndStablePrompt(t *testing.T) {
	model, _ := metadataModel(`{"conditions":[{"key":"serial","op":"is","value":9007199254740993}],"logic":"and"}`)
	old := metaFilterTemplateCache
	metaFilterTemplateCache = "{{metadata_keys}}"
	t.Cleanup(func() { metaFilterTemplateCache = old })
	metadata := common.MetaData{"serial": {"9007199254740993": {"doc"}}}
	result, err := GenMetaFilter(t.Context(), model, metadata, "question", nil)
	if err != nil || len(result.Conditions) != 1 || result.Conditions[0].Value != json.Number("9007199254740993") {
		t.Fatal("generated operand rounded", result, err)
	}
	ids, empty, err := ApplyMetaDataFilter(t.Context(), map[string]interface{}{"method": "auto"}, metadata, "question", model, nil, nil)
	if err != nil || empty || !reflect.DeepEqual(ids, []string{"doc"}) {
		t.Fatal(ids, empty, err)
	}
}
