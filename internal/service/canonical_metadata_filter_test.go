func TestSemiAutoGeneratedPredicatesStayWithinSelectedFields(t *testing.T) {
	model, driver := metadataModel(`{"conditions":[{"key":"status","op":"is","value":"Ready"}],"logic":"and"}`)
	old := metaFilterTemplateCache
	metaFilterTemplateCache = "metadata={{ metadata_keys }} constraints={{ constraints }}"
	t.Cleanup(func() { metaFilterTemplateCache = old })
	driver.check = func(_ *models.APIConfig, messages []models.Message) {
		system := messages[0].Content.(string)
		if !strings.Contains(system, `"version":`) || strings.Contains(system, `"status":`) {
			t.Fatal("unselected fields entered prompt", system)
		}
	}
	if _, _, err := ApplyMetaDataFilter(t.Context(), map[string]interface{}{"method": "semi_auto", "semi_auto": []interface{}{map[string]interface{}{"key": "version", "op": "is"}}}, metadataFixture(), "q", model, []string{"new"}, nil); err == nil {
		t.Fatal("unselected generated predicate accepted")
	}
}
