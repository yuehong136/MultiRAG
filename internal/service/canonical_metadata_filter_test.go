func metadataFixture() common.MetaData {
	return common.MetaData{"status": {"Ready": {"new", "old"}, "Draft": {"draft"}}, "version": {"v1": {"old"}, "v2": {"new", "draft"}}, "number": {"0": {"zero"}, "10": {"ten"}}, "boolean": {"false": {"false"}, "true": {"true"}}}
}
func manualMetadataConfig(conditions []MetaFilterCondition, logic string) map[string]interface{} {
	items := make([]interface{}, 0, len(conditions))
	for _, condition := range conditions {
		items = append(items, map[string]interface{}{"key": condition.Key, "op": condition.Op, "value": condition.Value})
	}
	return map[string]interface{}{"method": "manual", "manual": items, "logic": logic}
}

type metadataResponseDriver struct {
	models.ModelDriver
	answer  string
	failure error
	calls   int
	check   func(*models.APIConfig, []models.Message)
}

func (d *metadataResponseDriver) ChatWithMessages(_ string, messages []models.Message, api *models.APIConfig, _ *models.ChatConfig) (*models.ChatResponse, error) {
	d.calls++
	if d.check != nil {
		d.check(api, messages)
	}
	if d.failure != nil {
		return nil, d.failure
	}
	return &models.ChatResponse{Answer: &d.answer}, nil
}
func metadataModel(answer string) (*models.ChatModel, *metadataResponseDriver) {
	d := &metadataResponseDriver{answer: answer}
	name := "controlled"
	return models.NewChatModel(d, &name, &models.APIConfig{}), d
}

func TestApplyMetaFilterUsesCommonMatcherWithActualDocumentSlices(t *testing.T) {
	for _, tc := range []struct {
		condition MetaFilterCondition
		want      []string
	}{{MetaFilterCondition{Key: "status", Op: "contains", Value: "READY"}, []string{"new", "old"}}, {MetaFilterCondition{Key: "version", Op: "is", Value: "v2"}, []string{"draft", "new"}}, {MetaFilterCondition{Key: "number", Op: "is", Value: 0}, []string{"zero"}}, {MetaFilterCondition{Key: "boolean", Op: "is", Value: false}, []string{"false"}}} {
		got, empty, err := ApplyMetaDataFilter(t.Context(), manualMetadataConfig([]MetaFilterCondition{tc.condition}, "and"), metadataFixture(), "question", nil, nil, nil)
		if err != nil || empty || !reflect.DeepEqual(got, tc.want) {
			t.Fatal(tc.condition, got, empty, err)
		}
	}
}
func TestMetadataFilterIntersectsBaseInEveryMode(t *testing.T) {
	for _, method := range []string{"manual", "auto", "semi_auto"} {
		for _, base := range [][]string{nil, {}, {"old", "new", "outside", "new"}} {
			conditions := []MetaFilterCondition{{Key: "version", Op: "is", Value: "v2"}}
			wire, _ := json.Marshal(MetaFilterResult{Conditions: conditions, Logic: "and"})
			model, driver := metadataModel(string(wire))
			filter := manualMetadataConfig(conditions, "and")
			filter["method"] = method
			filter["semi_auto"] = []interface{}{"version"}
			got, empty, err := ApplyMetaDataFilter(t.Context(), filter, metadataFixture(), "question", model, base, nil)
			if err != nil {
				t.Fatal(err)
			}
			if base == nil {
				if !reflect.DeepEqual(got, []string{"draft", "new"}) || empty {
					t.Fatal(method, got, empty)
				}
			} else if len(base) == 0 {
				if got == nil || len(got) != 0 || !empty || driver.calls != 0 {
					t.Fatal("empty selection broadened", method, got, empty, driver.calls)
				}
			} else if !reflect.DeepEqual(got, []string{"new"}) || empty {
				t.Fatal(method, got, empty)
			}
		}
	}
}
